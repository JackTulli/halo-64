			remaining_profile_count = (word)(required_profile_count - (word)profile_count);
			do
			{
				*(long *)((byte *)widget->generated_list + profile_offset) = NONE;
				profile_count++;
				profile_offset += sizeof(long);
			} while (--remaining_profile_count);

void multiplayer_game_directions(
	struct widget_instance *widget)
{
	struct network_game *game = network_game_get_game();
	struct network_game_server *server = global_network_game_server_get();

	match_vassert(
		"c:\\halo\\SOURCE\\interface\\ui_widget_game_data_input_functions.c",
		0xBAD,
		widget->type == _ui_widget_type_text_box,
		"expected text box widget for team game directions");

	if (server)
	{
		if (!network_game_is_splitscreen_local() &&
			game &&
			game->machine_count < 2)
		{
			widget->parameters.text_box.string_list_index =
				_multiplayer_game_text_string_waiting_for_machine;
			widget->visible = TRUE;
			return;
		}

		if (network_game_is_splitscreen_local() &&
			game &&
			game->player_count < 2)
		{
			widget->parameters.text_box.string_list_index =
				_multiplayer_game_text_string_waiting_for_player;
			widget->visible = TRUE;
			return;
		}
	}

	if (game &&
		game->variant.has_teams == TRUE &&
		network_game_client_get_seconds_to_game_start(global_network_game_client_get()) < 0)
	{
		long team_zero_player_count = 0;
		long team_one_player_count = 0;
		long player_index;

		for (player_index = 0;
			player_index < NUMBEROF(game->players);
			player_index++)
		{
			if (network_player_is_valid(&game->players[player_index]))
			{
				switch (game->players[player_index].team_index)
				{
				case _team_red:
					team_zero_player_count++;
					break;
				case _team_blue:
					team_one_player_count++;
					break;
				}
			}
		}

		if (team_zero_player_count && team_one_player_count)
		{
			widget->parameters.text_box.string_list_index =
				_multiplayer_game_text_string_teams_ready;
			widget->visible = TRUE;
			return;
		}

		widget->parameters.text_box.string_list_index =
			_multiplayer_game_text_string_waiting_for_teams;
		widget->visible = TRUE;
		return;
	}

	widget->visible = FALSE;
	return;
}


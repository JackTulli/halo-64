/* ---------- private code */

static int list_indices_sort_proc(
	void const *index1,
	void const *index2)
{
	long first = *(long const *)index1;
	long second = *(long const *)index2;

	if (first == NONE)
	{
		if (second != first)
			return 1;
	}
	else if (second == NONE)
		return second;
	return 0;
}

static long filter_invalid_list_indices(
	long *indices,
	long number_of_items)
{
	long count;

	qsort(indices, number_of_items, sizeof(long), list_indices_sort_proc);
	for (count = 0; count < number_of_items; count++)
	{
		if (indices[count] == NONE)
			break;
	}
	return count;
}

